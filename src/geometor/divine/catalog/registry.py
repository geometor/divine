FAMILIES_BY_SLUG: dict[str, FamilySpec] = {fam.slug: fam for fam in FAMILIES}

CATALOG: tuple[ConstructionSpec, ...] = (
    *MINIMAL_COMPASS_SPECS,
    *EQUILATERAL_HEXAGON_SPECS,
    *SQUARES_RECTANGLES_SPECS,
    *RIGHT_AND_345_SPECS,
    *PENTAGONS_POLYGONS_SPECS,
    *CIRCLES_SANGAKU_SPECS,
    *RHOMBI_TRAPEZOIDS_ALGEBRA_SPECS,
)

CATALOG_BY_SLUG: dict[str, ConstructionSpec] = {
    f"{spec.family_slug}/{spec.slug}": spec for spec in CATALOG
}
CATALOG_BY_SHORT_SLUG: dict[str, ConstructionSpec] = {spec.slug: spec for spec in CATALOG}
CATALOG_BY_CODE: dict[str, ConstructionSpec] = {spec.catalog_code: spec for spec in CATALOG}


def get_family(family_slug: str) -> FamilySpec:
    """Look up a :class:`FamilySpec` by its directory slug."""
    return FAMILIES_BY_SLUG[family_slug]


def get_construction(identifier: str) -> ConstructionSpec:
    """Look up a :class:`ConstructionSpec` by catalog code, ``family/slug``, or ``slug``."""
    if identifier in CATALOG_BY_CODE:
        return CATALOG_BY_CODE[identifier]
    if identifier in CATALOG_BY_SLUG:
        return CATALOG_BY_SLUG[identifier]
    if identifier in CATALOG_BY_SHORT_SLUG:
        return CATALOG_BY_SHORT_SLUG[identifier]
    msg = f"Unknown Golden Ratio Catalog construction: {identifier!r}"
    raise KeyError(msg)


def build_construction(identifier: str) -> tuple[Model, GoldenCertificate]:
    """Build and symbolically certify a cataloged construction by identifier."""
    spec = get_construction(identifier)
    return certify_construction(spec)


def iter_catalog(family_slug: str | None = None) -> Iterator[ConstructionSpec]:
    """Iterate over catalog entries in canonical order, optionally filtered by family."""
    for spec in CATALOG:
        if family_slug is None or spec.family_slug == family_slug:
            yield spec
